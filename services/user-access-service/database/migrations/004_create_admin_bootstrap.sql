-- Bootstrap history is retained even if the initial administrator account is later removed.
DECLARE
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE ADMIN_BOOTSTRAP_STATE (
    BOOTSTRAP_ID NUMBER PRIMARY KEY CHECK (BOOTSTRAP_ID = 1),
    ADMIN_USER_ID VARCHAR2(128) NOT NULL,
    TOKEN_HASH VARCHAR2(64) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL)';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
